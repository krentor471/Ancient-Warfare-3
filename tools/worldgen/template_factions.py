#!/usr/bin/env python3
"""Rebuild assets/ancientwarfare/template_factions.txt.

Each line is "<template path>=<faction>;<soldiers>;<civilians>". A template in a nation or tribe folder
(AWNationEmpire, AWTribalZimba) belongs to that faction; any other template
belongs to the faction most of its spawners belong to. Templates without either
are left out and count as neutral. Soldiers and civilians count that faction's
spawner entries, the garrison and people a settlement starts with. Run after
adding or changing templates.
"""
import collections
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[2] / "src/main/resources/assets/ancientwarfare"
SPAWNER = re.compile(rb'factionName:"(\w+)"')
SPAWN_ENTRY = re.compile(rb'factionName:"(\w+)".*?entityId:"[^"]*faction\.([\w.]+)"')
CIVILIAN_ROLES = ("civilian", "trader", "bard", "priest")
FACTION_FOLDER = re.compile(r"/AW(?:Nation|Tribal)([A-Za-z]+)/")
FACTIONS = sorted(
    (f["name"] for f in json.loads((ROOT.parent.parent / "data/ancientwarfare/npc/factions.json").read_text(encoding="utf-8"))["factions"]),
    key=len,
    reverse=True,
)


def folder_faction(path):
    match = FACTION_FOLDER.search(path)
    if match:
        folder = match.group(1).lower()
        for faction in FACTIONS:
            if folder.startswith(faction):
                return faction
    return None


lines = []
for path in (ROOT / "template_index.txt").read_text(encoding="utf-8-sig").splitlines():
    path = path.strip()
    file = ROOT / "template" / path
    if not path or not file.is_file():
        continue
    data = file.read_bytes()
    faction = folder_faction(path)
    if faction is None:
        counts = collections.Counter(SPAWNER.findall(data))
        faction = counts.most_common(1)[0][0].decode() if counts else None
    if faction:
        soldiers = civilians = 0
        for owner, role in SPAWN_ENTRY.findall(data):
            if owner.decode() == faction:
                if role.decode().startswith(CIVILIAN_ROLES):
                    civilians += 1
                else:
                    soldiers += 1
        lines.append(f"{path}={faction};{soldiers};{civilians}")

(ROOT / "template_factions.txt").write_text(
    "# Generated by tools/worldgen/template_factions.py\n" + "\n".join(lines) + "\n", encoding="utf-8"
)
print(f"{len(lines)} faction templates")
